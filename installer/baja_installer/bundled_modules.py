"""Which Python modules the frozen exe must contain.

PyInstaller follows `import` statements, but it cannot see modules that are
imported by name at run time. The build therefore passes every module
listed here as a hidden import, and `BajaWorker.exe --check` imports each
one, so a missing module shows up in CI instead of on a volunteer's PC.
`tests/installer/test_bundled_modules.py` imports the same list on Linux.
"""

import importlib
import pkgutil

# Every submodule of these packages is bundled.
BUNDLED_PACKAGES = ("worker", "shared", "baja_installer")

# Test helpers that ship inside `shared` but are never used at run time.
EXCLUDED_MODULE_PREFIXES = ("shared.testing",)

# uvicorn chooses its event loop, HTTP protocol and lifespan handler from
# strings in uvicorn.config ("uvicorn.loops.auto:auto_loop_setup", …), so
# static analysis never sees these. h11_impl is the HTTP protocol "auto"
# falls back to when httptools is not installed (it is not).
RUNTIME_IMPORTED_MODULES = (
    "uvicorn.lifespan.off",
    "uvicorn.lifespan.on",
    "uvicorn.logging",
    "uvicorn.loops.asyncio",
    "uvicorn.loops.auto",
    "uvicorn.protocols.http.auto",
    "uvicorn.protocols.http.h11_impl",
    "uvicorn.protocols.websockets.auto",
)


def _is_excluded(module_name: str) -> bool:
    return any(
        module_name == prefix or module_name.startswith(prefix + ".")
        for prefix in EXCLUDED_MODULE_PREFIXES
    )


def submodules_of(package_name: str) -> list[str]:
    """The package itself and every module below it, found on disk."""
    package = importlib.import_module(package_name)
    names = [package_name]
    for module in pkgutil.walk_packages(package.__path__, prefix=package_name + "."):
        names.append(module.name)
    return names


def discover_bundled_modules() -> list[str]:
    """The full sorted list, computed from the source tree (build time)."""
    names: set[str] = set(RUNTIME_IMPORTED_MODULES)
    for package_name in BUNDLED_PACKAGES:
        names.update(name for name in submodules_of(package_name) if not _is_excluded(name))
    # _build_info is generated by the build and is listed by walk_packages
    # only when it already exists; it is always bundled.
    names.add("baja_installer._build_info")
    return sorted(names)
